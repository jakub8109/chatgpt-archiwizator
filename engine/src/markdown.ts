import { IMAGE_EXT } from './html.js';
import type { NormalizedConversation } from './types.js';

/*
 * Security model of the .md files
 * --------------------------------
 * Conversation text is untrusted, and Markdown viewers (VS Code preview, Obsidian, GitHub) render raw HTML,
 * images and links — e.g. an image at \\host\share\x.png makes Windows send the NTLM hash over SMB.
 * Sanitising Markdown is a losing game (every parser differs on code spans, fences, containers, entities, line
 * breaks inside destinations). So the .md never lets untrusted text be interpreted at all:
 *   - each message's text goes into a fenced code block whose fence is longer than any backtick run in the text,
 *     so CommonMark cannot close it early and nothing inside is parsed (no HTML, no links, no images);
 *   - everything outside the fences is generated by us: links/images only to this archive's attachments/, and
 *     untrusted short strings (title, file names, model) are backslash-escaped.
 * The formatted reading view is the HTML archive (html.ts, escaped + CSP).
 */

/** Backslash-escape every Markdown/HTML-significant ASCII punctuation character (CommonMark: all are escapable). */
export function mdEscape(s: string): string {
  return s.replace(/[\r\n]+/g, ' ').replace(/[\\`*_{}[\]()<>#+\-.!|~&"':;=?@^$%/]/g, '\\$&');
}

/** Fenced block that the text cannot close: the fence is longer than the longest backtick run inside. */
export function fenced(text: string): string {
  const longest = Math.max(0, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
  const fence = '`'.repeat(Math.max(3, longest + 1));
  return `${fence}text\n${text}\n${fence}`;
}

/** Link target to our own attachment (path generated by us): percent-encode everything unusual. */
const linkTo = (p: string) => encodeURI(p).replace(/[()[\]<>'"]/g, (c) => '%' + c.charCodeAt(0).toString(16).toUpperCase());

const ROLE_LABEL: Record<string, string> = { user: 'Użytkownik', assistant: 'ChatGPT', system: 'System', tool: 'Narzędzie' };

function yamlStr(s: string): string {
  return JSON.stringify(s);   // JSON strings are valid YAML scalars (front matter is metadata, not rendered)
}

/**
 * Markdown for one conversation. `savedFiles` maps fileId -> path relative to the conversation folder
 * (only files that were actually downloaded); other references are kept as a visible note.
 */
export function toMarkdown(conv: NormalizedConversation, savedFiles: Record<string, string> = {}): string {
  const out = [
    '---',
    `source: chatgpt`,
    `conversation_id: ${yamlStr(conv.id)}`,
    `title: ${yamlStr(conv.title)}`,
    `created: ${conv.createdAt ?? 'null'}`,
    `updated: ${conv.updatedAt ?? 'null'}`,
    `model: ${conv.model ? yamlStr(conv.model) : 'null'}`,
    `messages: ${conv.messages.length}`,
    `branches: ${conv.branchCount}`,
    `archived: ${conv.archived}`,
    `url: ${yamlStr('https://chatgpt.com/c/' + conv.id)}`,
    '---',
    '',
    `# ${mdEscape(conv.title)}`,
    '',
  ];
  if (conv.branchCount > 1) {
    out.push(`> Rozmowa ma ${conv.branchCount} gałęzie (edytowane/regenerowane odpowiedzi). Poniżej gałąź widoczna w ChatGPT; wszystkie są w \`raw.json\`.`, '');
  }
  out.push('> Treść wiadomości jest zapisana dosłownie (jako tekst). Sformatowany widok ze zdjęciami: `conversation.html`.', '');

  for (const m of conv.messages) {
    const label = ROLE_LABEL[m.role] ?? mdEscape(m.role);
    // local wall-clock time (the ISO/UTC timestamps stay in metadata.json and the front matter)
    const local = m.createdAt ? new Date(m.createdAt).toLocaleString('pl-PL', { dateStyle: 'short', timeStyle: 'short' }) : null;
    const meta = [local, m.model ? mdEscape(m.model) : null].filter(Boolean).join(' · ');
    out.push('---', '', `**${label}**${meta ? ` · ${meta}` : ''}`, '');
    // inline image placeholders become a readable note inside the (inert) text
    const text = m.text.replace(/!\[[^\]\n]*\]\(attachment:([A-Za-z0-9_-]+)\)|attachment:([A-Za-z0-9_-]+)/g,
      (_s, a?: string, b?: string) => `[obraz: ${savedFiles[(a ?? b)!] ?? 'nie pobrano'}]`);
    if (text.trim()) out.push(fenced(text), '');
    const files = m.files;
    if (files.length) {
      out.push('**Załączniki:**', '');
      for (const f of files) {
        const p = savedFiles[f.fileId];
        const name = mdEscape(f.name);
        if (!p) out.push(`- ${name} _(nie pobrano)_`);
        else if (IMAGE_EXT.test(p)) out.push(`- ![${name}](${linkTo(p)})`);
        else out.push(`- [${name}](${linkTo(p)})`);
      }
      out.push('');
    }
  }
  return out.join('\n') + '\n';
}
